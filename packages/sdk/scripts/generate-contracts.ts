// Generate src/contracts from the Rust-owned contracts. Run from any directory.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { renderSchemaDeclarations } from './json-schema-declarations.ts';

const packageDirectory = fileURLToPath(new URL('../', import.meta.url));
const repositoryDirectory = fileURLToPath(new URL('../../../', import.meta.url));
const contractsDirectory = join(packageDirectory, 'src', 'contracts');

/** Command-local Apple SDK correction for C dependencies; other hosts use their toolchain. */
function cargoEnvironment(): NodeJS.ProcessEnv {
	if (process.platform !== 'darwin' || process.env['SDKROOT'] !== undefined) return process.env;
	const sdk = execFileSync('xcrun', ['--show-sdk-path'], { encoding: 'utf8' }).trim();
	return { ...process.env, SDKROOT: sdk, CC: '/usr/bin/clang', CFLAGS: `-isysroot ${sdk}` };
}

const output = mkdtempSync(join(tmpdir(), 'sunstack-sdk-contracts-'));
try {
	execFileSync(
		'cargo',
		[
			'run',
			'--locked',
			'--quiet',
			'-p',
			'sunstack-sdk-native',
			'--features',
			'generation',
			'--bin',
			'export-sdk-contracts',
			'--',
			output,
		],
		{ cwd: repositoryDirectory, stdio: 'inherit', env: cargoEnvironment() },
	);
	writeFileSync(
		join(contractsDirectory, 'contracts.ts'),
		readFileSync(join(output, 'contracts.ts'), 'utf8'),
	);
	const wide: unknown = JSON.parse(readFileSync(join(output, 'wide-integers.json'), 'utf8'));
	if (
		typeof wide !== 'object' ||
		wide === null ||
		!('definitions' in wide) ||
		!('document_roots' in wide)
	) {
		throw new Error('wide-integers.json has no definitions or document roots');
	}
	writeFileSync(
		join(contractsDirectory, 'wide-integers.ts'),
		[
			'// Generated by export-sdk-contracts: where full-width integers sit. Do not edit.',
			"import type { SdkDocumentValue } from './contracts.ts';",
			"import type { WideDefinition, WideShape } from './wide-integer-shapes.ts';",
			'',
			`export const wideIntegerDefinitions = ${JSON.stringify(wide.definitions, null, '\t')} as const satisfies Readonly<Record<string, WideDefinition>>;`,
			'',
			`export const documentRootShapes = ${JSON.stringify(wide.document_roots, null, '\t')} as const satisfies Readonly<Record<SdkDocumentValue['kind'], WideShape | null>>;`,
			'',
		].join('\n'),
	);
	const contract: unknown = JSON.parse(readFileSync(join(output, 'contract.json'), 'utf8'));
	if (
		typeof contract !== 'object' ||
		contract === null ||
		!('contract_revision' in contract) ||
		typeof contract.contract_revision !== 'number'
	) {
		throw new Error('contract.json has no contract_revision');
	}
	writeFileSync(
		join(contractsDirectory, 'contract-revision.ts'),
		[
			'// Generated by export-sdk-contracts. Do not edit.',
			'/** The native contract revision these declarations describe. */',
			`export const CONTRACT_REVISION = ${contract.contract_revision};`,
			'',
		].join('\n'),
	);
	const schema: unknown = JSON.parse(readFileSync(join(output, 'ast-grep.schema.json'), 'utf8'));
	writeFileSync(join(contractsDirectory, 'ast-grep.ts'), renderSchemaDeclarations(schema));
	execFileSync(join(repositoryDirectory, 'node_modules', '.bin', 'oxfmt'), [contractsDirectory], {
		cwd: repositoryDirectory,
		stdio: 'inherit',
	});
} finally {
	rmSync(output, { recursive: true, force: true });
}
